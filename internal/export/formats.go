// Package export is textarea's lib/formats.js: one note, nine file formats.
// Every converter is byte for byte the browser's, so a note saved from the
// terminal is the file the web app would have written.
package export

import (
	"regexp"
	"strconv"
	"strings"
	"time"
	"unicode/utf16"

	"github.com/Gitguy268/textarea-cli/internal/note"
)

// Note is the shape every exporter takes. Hash includes its '#'.
type Note struct {
	Text, Title, Style, Hash string
	ExportedAt               string
}

// ISO is Date.prototype.toISOString.
func ISO(t time.Time) string { return t.UTC().Format("2006-01-02T15:04:05.000Z") }

// Format is one entry of the registry.
type Format struct{ ID, Label, Ext, Mime string }

// Formats is the registry, in menu order.
var Formats = []Format{
	{"txt", "Plain text", "txt", "text/plain"},
	{"md", "Markdown", "md", "text/markdown"},
	{"html", "HTML page", "html", "text/html"},
	{"json", "JSON", "json", "application/json"},
	{"csv", "CSV", "csv", "text/csv"},
	{"xml", "XML", "xml", "application/xml"},
	{"rtf", "RTF (Word)", "rtf", "application/rtf"},
	{"tex", "LaTeX", "tex", "application/x-tex"},
	{"yml", "YAML", "yml", "text/yaml"},
}

// GetFormat falls back to plain text, like getFormat.
func GetFormat(id string) Format {
	for _, f := range Formats {
		if f.ID == id {
			return f
		}
	}
	return Formats[0]
}

func escapeXMLText(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

func escapeXMLAttribute(s string) string {
	return strings.ReplaceAll(escapeXMLText(s), `"`, "&quot;")
}

var formulaPrefix = regexp.MustCompile("^[=+\\-@\t\r]")

// ToCSV is RFC 4180, one row per line, formula prefixes neutralised.
func ToCSV(text string) string {
	rows := []string{"line,text"}
	var lines []string
	if text != "" {
		lines = strings.Split(text, "\n")
	}
	if len(lines) > 1 && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	for i, line := range lines {
		cell := line
		if formulaPrefix.MatchString(line) {
			cell = "'" + line
		}
		rows = append(rows, strconv.Itoa(i+1)+`,"`+strings.ReplaceAll(cell, `"`, `""`)+`"`)
	}
	return strings.Join(rows, "\r\n") + "\r\n"
}

func jsonOrNull(s string) string {
	if s == "" {
		return "null"
	}
	return note.JSONString(s)
}

func toJSON(n Note) string {
	return "{\n" +
		`  "title": ` + note.JSONString(n.Title) + ",\n" +
		`  "exportedAt": ` + note.JSONString(n.ExportedAt) + ",\n" +
		`  "hash": ` + note.JSONString(n.Hash) + ",\n" +
		`  "style": ` + jsonOrNull(n.Style) + ",\n" +
		`  "text": ` + note.JSONString(n.Text) + "\n}\n"
}

func toXML(n Note) string {
	lines := []string{
		`<?xml version="1.0" encoding="UTF-8"?>`,
		`<note xmlns="https://textarea.my/ns/1">`,
		"  <title>" + escapeXMLText(n.Title) + "</title>",
		"  <exportedAt>" + escapeXMLText(n.ExportedAt) + "</exportedAt>",
	}
	if n.Hash != "" {
		lines = append(lines, "  <source>"+escapeXMLText(n.Hash)+"</source>")
	}
	if n.Style != "" {
		lines = append(lines, "  <style>"+escapeXMLText(n.Style)+"</style>")
	}
	lines = append(lines, "  <text><![CDATA["+strings.ReplaceAll(n.Text, "]]>", "]]]]><![CDATA[>")+"]]></text>", "</note>")
	return strings.Join(lines, "\n")
}

// ToRTF is RTF 1.0 with every code unit above 127 escaped.
func ToRTF(text string) string {
	var b strings.Builder
	for _, u := range utf16.Encode([]rune(text)) {
		switch {
		case u == '\\':
			b.WriteString(`\\`)
		case u == '{':
			b.WriteString(`\{`)
		case u == '}':
			b.WriteString(`\}`)
		case u == '\n':
			b.WriteString("\\par\n")
		case u == '\t':
			b.WriteString(`\tab `)
		case u < 128:
			b.WriteByte(byte(u))
		default:
			code := int(u)
			if code > 32767 {
				code -= 65536
			}
			b.WriteString(`\u` + strconv.Itoa(code) + "?")
		}
	}
	return strings.Join([]string{
		`{\rtf1\ansi\ansicpg1252\deff0`,
		`{\fonttbl{\f0\fnil\fcharset0 Helvetica;}}`,
		`{\colortbl;\red0\green0\blue0;}`,
		`\f0\fs22 `,
		b.String(),
		"}",
	}, "\n") + "\n"
}

var (
	texSpecials = regexp.MustCompile(`[\\{}$&#^_~%]`)
	fenceBlock  = regexp.MustCompile("(?m)^(```[^\\n]*\\n[\\s\\S]*?\\n```|~~~[^\\n]*\\n[\\s\\S]*?\\n~~~)$")
	fenceHead   = regexp.MustCompile("^(```|~~~)[^\\n]*\\n")
	fenceTail   = regexp.MustCompile("\\n(```|~~~)$")
	fenceStart  = regexp.MustCompile("^(```|~~~)")
)

func texEscape(line string) string {
	return texSpecials.ReplaceAllStringFunc(line, func(c string) string { return `\` + c })
}

// ToTex is a LaTeX article, fenced code as verbatim.
func ToTex(n Note) string {
	date := n.ExportedAt
	if len(date) > 10 {
		date = date[:10]
	}
	out := []string{
		"% Generated by textarea.my",
		`\documentclass[11pt,a4paper]{article}`,
		`\usepackage[utf8]{inputenc}`,
		`\usepackage[T1]{fontenc}`,
		`\usepackage[margin=2.5cm]{geometry}`,
		`\usepackage{parskip}`,
		`\usepackage{hyperref}`,
		"",
		`\title{` + texEscape(n.Title) + "}",
		`\date{` + texEscape(date) + "}",
		"",
		`\begin{document}`,
		`\maketitle`,
		"",
	}
	// String.prototype.split with a capturing group: the text between the
	// fences and the fences themselves, in order.
	var blocks []string
	last := 0
	for _, loc := range fenceBlock.FindAllStringIndex(n.Text, -1) {
		blocks = append(blocks, n.Text[last:loc[0]], n.Text[loc[0]:loc[1]])
		last = loc[1]
	}
	blocks = append(blocks, n.Text[last:])
	for _, block := range blocks {
		if block == "" {
			continue
		}
		if fenceStart.MatchString(block) {
			code := fenceTail.ReplaceAllString(fenceHead.ReplaceAllString(block, ""), "")
			out = append(out, `\begin{verbatim}`, code, `\end{verbatim}`, "")
		} else {
			for _, line := range strings.Split(block, "\n") {
				out = append(out, texEscape(line))
			}
			out = append(out, "")
		}
	}
	out = append(out, `\end{document}`)
	return strings.Join(out, "\n")
}

var (
	ambiguous    = regexp.MustCompile(`(?i)^(?:true|false|null|yes|no|on|off|~|-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?|\.inf|\.nan)$`)
	nonPrint     = regexp.MustCompile(`[^\x20-\x7e]`)
	yamlLead     = regexp.MustCompile("^[\\s>|&*!%@`?{}\\[\\],#-]")
	yamlColon    = regexp.MustCompile(`:\s|\s#`)
	yamlColonEnd = regexp.MustCompile(`:\s*$`)
)

func yamlScalar(v string) string {
	if nonPrint.MatchString(v) || v == "" || ambiguous.MatchString(v) || yamlLead.MatchString(v) ||
		yamlColon.MatchString(v) || yamlColonEnd.MatchString(v) {
		return note.JSONString(v)
	}
	return v
}

// ToYAML is a YAML document with the note as a literal block.
func ToYAML(n Note) string {
	lines := []string{"title: " + yamlScalar(n.Title), "exportedAt: " + yamlScalar(n.ExportedAt)}
	if n.Hash != "" {
		lines = append(lines, "source: "+yamlScalar(n.Hash))
	}
	if n.Style != "" {
		lines = append(lines, "style: "+yamlScalar(n.Style))
	}
	lines = append(lines, "text: |-")
	for _, line := range strings.Split(strings.TrimSuffix(n.Text, "\n"), "\n") {
		if line == "" {
			lines = append(lines, "")
		} else {
			lines = append(lines, "  "+line)
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

// The page the browser falls back to when it has no rendered markup to hand.
const fallbackCSS = "body { font: 18px/1.5 system-ui; white-space: pre-wrap; }"

func toHTML(n Note) string {
	parts := []string{
		"<!DOCTYPE html>",
		`<html lang="en">`,
		"<head>",
		`<meta charset="utf-8">`,
		`<meta name="viewport" content="width=device-width, initial-scale=1">`,
		"<title>" + escapeXMLText(n.Title) + "</title>",
		`<meta name="generator" content="textarea.my">`,
		`<meta name="exportedAt" content="` + escapeXMLAttribute(n.ExportedAt) + `">`,
	}
	if n.Hash != "" {
		parts = append(parts, `<meta name="source" content="`+escapeXMLAttribute(n.Hash)+`">`)
	}
	parts = append(parts,
		"<style>"+fallbackCSS+"</style>",
		"</head>",
		"<body>",
		"<pre>"+escapeXMLText(n.Text)+"</pre>",
		"</body>",
		"</html>",
		"",
	)
	return strings.Join(parts, "\n")
}

// Convert renders a note in a format.
func Convert(n Note, id string) (text, mime string) {
	f := GetFormat(id)
	switch f.ID {
	case "html":
		return toHTML(n), f.Mime
	case "md":
		if strings.HasSuffix(n.Text, "\n") {
			return n.Text, f.Mime
		}
		return n.Text + "\n", f.Mime
	case "json":
		return toJSON(n), f.Mime
	case "csv":
		return ToCSV(n.Text), f.Mime
	case "xml":
		return toXML(n), f.Mime
	case "rtf":
		return ToRTF(n.Text), f.Mime
	case "tex":
		return ToTex(n), f.Mime
	case "yml":
		return ToYAML(n), f.Mime
	}
	return n.Text, f.Mime
}
